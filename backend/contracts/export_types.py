"""`make types`: contract models -> frontend/src/contracts/schema.json -> index.ts.

Run by the Integrator after every contract change; tests/contract checks schema.json is up to date.
"""

import json
import shutil
import subprocess
from pathlib import Path
from typing import Any

from pydantic.json_schema import models_json_schema

from backend.contracts.artifacts import Bom, EnclosureManifest, RunManifest, Wiring
from backend.contracts.events import Event, Question, Todo
from backend.contracts.hardware import Hardware
from backend.contracts.parts import BoardDef, PartDef
from backend.contracts.results import ToolResult
from backend.contracts.runner import AnswerRequest, EditRequest, RunRequest, RunSummary
from backend.contracts.spec import Layout, ProjectSpec

FRONTEND = Path(__file__).resolve().parents[2] / "frontend"
OUT = FRONTEND / "src" / "contracts"
MODELS = [
    ProjectSpec,
    Layout,
    PartDef,
    BoardDef,
    ToolResult,
    Event,
    Todo,
    Question,
    RunRequest,
    EditRequest,
    AnswerRequest,
    RunSummary,
    RunManifest,
    Wiring,
    Bom,
    EnclosureManifest,
    Hardware,
]


def _for_json2ts(node: Any) -> Any:
    """json2ts makes a type alias per titled property and doesn't read draft 2020-12 tuples:
    drop property titles and turn prefixItems into the older tuple form."""
    if isinstance(node, list):
        return [_for_json2ts(v) for v in node]
    if not isinstance(node, dict):
        return node
    node = {k: _for_json2ts(v) for k, v in node.items()}
    if "prefixItems" in node:
        node["items"] = node.pop("prefixItems")
    for prop in node.get("properties", {}).values():
        prop.pop("title", None)
    return node


def schema() -> dict:
    _, top = models_json_schema(
        [(m, "serialization") for m in MODELS], title="P2DContracts"
    )
    return _for_json2ts(top)


def schema_text() -> str:
    return json.dumps(schema(), indent=2, sort_keys=True) + "\n"


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "schema.json").write_text(schema_text())
    banner = "// Generated by `make types` from backend/contracts. Do not edit."
    subprocess.run(
        [
            shutil.which("npx") or "npx",  # npx.cmd on Windows
            "json2ts",
            "--input",
            "src/contracts/schema.json",
            "--output",
            "src/contracts/index.ts",
            "--unreachableDefinitions",
            "--bannerComment",
            banner,
        ],
        cwd=FRONTEND,
        check=True,
    )


if __name__ == "__main__":
    main()
